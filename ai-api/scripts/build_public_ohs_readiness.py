def write_csv(path: Path, rows, columns):
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, columns, lineterminator="\r\n")
    writer.writeheader()
    for row in rows:
        writer.writerow({c: row.get(c, "") for c in columns})
    path.write_text("﻿" + buffer.getvalue(), encoding="utf-8")


