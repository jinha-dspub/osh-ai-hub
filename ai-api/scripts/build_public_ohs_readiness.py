def hwp_text(path: Path):
    import olefile

    ole = olefile.OleFileIO(str(path))
    compressed = ole.openstream("FileHeader").read()[36] & 1
    out = []
    sections = sorted([s for s in ole.listdir() if s[0] == "BodyText"], key=lambda s: int(s[1][7:]))
    for section in sections:
        data = ole.openstream(section).read()
        if compressed:
            data = zlib.decompress(data, -15)
        i = 0
        while i < len(data):
            header = struct.unpack_from("<I", data, i)[0]
            i += 4
            tag, size = header & 0x3FF, (header >> 20) & 0xFFF
            if size == 0xFFF:
                size = struct.unpack_from("<I", data, i)[0]
                i += 4
            if tag == 67:
                raw, j, chars = data[i : i + size], 0, []
                while j < len(raw):
                    c = struct.unpack_from("<H", raw, j)[0]
                    if c < 32:
                        skip = (
                            16 if c in (1, 2, 3, 9, 11, 12, 14, 15, 16, 17, 18, 21, 22, 23) else 2
                        )
                        if c in (10, 13):
                            chars.append("\n")
                        j += skip
                        continue
                    chars.append(chr(c))
                    j += 2
                out.append("".join(chars))
            i += size
    return "\n".join(out)


def file_text(path: Path):
    if path.suffix == ".html":
        s = re.sub(
            r"<script.*?</script>|<style.*?</style>",
            "",
            path.read_text("utf-8", "ignore"),
            flags=re.DOTALL,
        )
        return html.unescape(re.sub(r"<[^>]+>", " ", s))
    if path.suffix == ".pdf":
        import pypdf

        return "\n".join((p.extract_text() or "") for p in pypdf.PdfReader(str(path)).pages)
    if path.suffix == ".hwp":
        return hwp_text(path)
    return ""


def squash(text: str):
    return re.sub(r"\s+", "", text)


def sha256(path: Path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


